#!/usr/bin/env python3
"""Build an original moka pot as standalone MuJoCo and LIBERO object MJCF.

All visual meshes and texture maps are generated by ``generate.py``.  The
two XML files differ only in who creates the free joint: standalone MJCF owns
one explicitly, while ``MujocoXMLObject`` adds it during LIBERO integration.
"""

from __future__ import annotations

import json
import xml.etree.ElementTree as ET
from pathlib import Path


HERE = Path(__file__).resolve().parent
OUT = HERE / "generated"

METAL_PARTS = {
    "lower_chamber": "aluminium",
    "boiler_foot": "dark_steel",
    "upper_chamber": "steel",
    "rim": "bright_steel",
    "closed_lid": "steel",
    "joint_band": "bright_steel",
    "hinge_socket": "dark_steel",
    "hinge_pin": "bright_steel",
    "grip_mount_upper": "dark_steel",
    "grip_mount_lower": "dark_steel",
    "pour_spout": "bright_steel",
    "spout_lip_left": "bright_steel",
    "spout_lip_right": "bright_steel",
    "pressure_valve": "bright_steel",
}
POLYMER_PARTS = {"lid_knob": "polymer", "curved_grip": "polymer", "seam_gasket": "gasket"}


def add_assets(root: ET.Element) -> None:
    assets = ET.SubElement(root, "asset")
    ET.SubElement(assets, "texture", {
        "name": "moka_brushed_aluminium_2k", "type": "2d",
        "file": "brushed_aluminium_albedo_2k.png",
    })
    ET.SubElement(assets, "texture", {
        "name": "moka_satin_grip_2k", "type": "2d",
        "file": "satin_grip_albedo_2k.png",
    })
    for name, rgba, texture, reflectance, shininess in [
        ("aluminium", "0.91 0.94 0.94 1", "moka_brushed_aluminium_2k", "0.33", "0.66"),
        ("steel", "0.96 0.97 0.96 1", "moka_brushed_aluminium_2k", "0.38", "0.72"),
        ("bright_steel", "1 1 0.99 1", "moka_brushed_aluminium_2k", "0.46", "0.82"),
        ("dark_steel", "0.38 0.41 0.42 1", "moka_brushed_aluminium_2k", "0.14", "0.48"),
        ("polymer", "0.72 0.75 0.77 1", "moka_satin_grip_2k", "0.03", "0.18"),
        ("gasket", "0.18 0.20 0.21 1", None, "0.02", "0.08"),
    ]:
        attrib = {"name": f"moka_{name}", "rgba": rgba,
                  "reflectance": reflectance, "shininess": shininess,
                  "specular": "0.58" if texture != "moka_satin_grip_2k" else "0.12"}
        if texture:
            attrib.update(texture=texture, texuniform="false", texrepeat="1 1")
        ET.SubElement(assets, "material", attrib)
    for name in sorted(METAL_PARTS | POLYMER_PARTS):
        if not (OUT / f"{name}.obj").is_file():
            raise FileNotFoundError(OUT / f"{name}.obj")
        ET.SubElement(assets, "mesh", {"name": f"moka_{name}",
                                       "file": f"{name}.obj", "inertia": "shell"})


def build_xml(with_joint: bool) -> ET.ElementTree:
    root = ET.Element("mujoco", {"model": "safevla_original_moka_pot"})
    ET.SubElement(root, "compiler", {"angle": "radian", "autolimits": "true"})
    ET.SubElement(root, "option", {"timestep": "0.002", "gravity": "0 0 -9.81"})
    add_assets(root)
    world = ET.SubElement(root, "worldbody")
    wrapper = world if with_joint else ET.SubElement(world, "body", {"name": "moka_wrapper"})
    body = ET.SubElement(wrapper, "body", {"name": "object"})
    site_parent = body if with_joint else wrapper
    # A 420 g cast-metal vessel with the centre of mass low in the boiler and
    # slightly toward the handle. The inertia is explicit so decorative meshes
    # and the lightweight grip do not introduce nonsensical dynamic mass.
    ET.SubElement(body, "inertial", {
        "pos": "0 0.004 -0.012", "mass": "0.420",
        "diaginertia": "0.00110 0.00118 0.00043",
    })
    if with_joint:
        ET.SubElement(body, "freejoint", {"name": "moka_free_joint"})
    for name, material in sorted((METAL_PARTS | POLYMER_PARTS).items()):
        ET.SubElement(body, "geom", {
            "name": f"visual_{name}", "type": "mesh", "mesh": f"moka_{name}",
            "material": f"moka_{material}", "group": "1", "mass": "0",
            "contype": "0", "conaffinity": "0",
        })
    proxy = json.loads((OUT / "collision_proxy.json").read_text())
    for index, shape in enumerate(proxy["geoms"]):
        ET.SubElement(body, "geom", {
            "name": f"contact_{index:02d}", "type": shape["type"],
            "pos": " ".join(f"{x:.6f}" for x in shape["pos"]),
            "size": " ".join(f"{x:.6f}" for x in shape["size"]),
            "group": "0", "rgba": "0.5 0.5 0.5 0.08",
            "mass": "0", "contype": "1", "conaffinity": "1",
            "friction": "0.95 0.3 0.1", "solref": "0.006 1",
            "solimp": "0.95 0.99 0.001",
        })
    ET.SubElement(site_parent, "site", {"name": "bottom_site", "pos": "0 0 -0.068",
                                    "size": "0.005", "rgba": "0 0 0 0"})
    ET.SubElement(site_parent, "site", {"name": "top_site", "pos": "0 0 0.084",
                                    "size": "0.005", "rgba": "0 0 0 0"})
    ET.SubElement(site_parent, "site", {"name": "horizontal_radius_site",
                                    "pos": "0.04 0 0", "size": "0.005", "rgba": "0 0 0 0"})
    ET.indent(root, space="  ")
    return ET.ElementTree(root)


def build() -> None:
    OUT.mkdir(exist_ok=True)
    for joint, filename in [(True, "moka_standalone.xml"),
                            (False, "moka_libero.xml")]:
        build_xml(joint).write(OUT / filename, encoding="utf-8", xml_declaration=True)


if __name__ == "__main__":
    build()
